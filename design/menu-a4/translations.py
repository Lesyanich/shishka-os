def key():
    return subprocess.run(
        ["security", "find-generic-password", "-s", "SUPABASE_SERVICE_ROLE_KEY", "-w"],
        capture_output=True, text=True, check=True).stdout.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    k = key()

    req = urllib.request.Request(
        f"{REST}/menu_public?is_web_visible=eq.true&select=product_code,name,section_name",
        headers={"apikey": k, "Authorization": f"Bearer {k}"})
    with urllib.request.urlopen(req) as r:
        rows = json.load(r)
    drinks = {"☕ Coffee", "🥤 Smoothies", "🧃 Juices", "🍵 Matcha"}
    food = [r for r in rows if r["section_name"] not in drinks]

    missing = [r["product_code"] for r in food if r["product_code"] not in T]
    extra = [c for c in T if c not in {r["product_code"] for r in food}]
    if missing:
        sys.exit(f"no translation for: {', '.join(missing)}")
    if extra:
        sys.exit(f"translation for a dish not on the menu: {', '.join(extra)}")
    print(f"{len(food)} food dishes, all translated")
    if not args.write:
        return

    for code, (ru, th) in T.items():
        body = json.dumps({"customer_description_ru": ru,
                           "customer_description_th": th}).encode()
        req = urllib.request.Request(
            f"{REST}/nomenclature?product_code=eq.{urllib.parse.quote(code)}",
            data=body, method="PATCH",
            headers={"apikey": k, "Authorization": f"Bearer {k}",
                     "Content-Type": "application/json",
                     "Prefer": "return=representation"})
        with urllib.request.urlopen(req) as r:
            n = len(json.load(r))
        if n != 1:
            print(f"  ! {code}: {n} rows", file=sys.stderr)
    print(f"wrote {len(T)} rows (translation_reviewed_at left NULL)")


if __name__ == "__main__":
    import urllib.parse
    main()
